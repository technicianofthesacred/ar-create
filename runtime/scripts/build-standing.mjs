// The browser's copy of where a subject stands: runtime/standing-rule.mjs, unchanged, as public/v2/shell/standing.js.
// It is an ES module (load it with `await import('/v2/shell/standing.js')`); it also leaves its names on
// globalThis.v2Standing for a screen that prefers a plain global once the module has loaded.
import fs from 'node:fs/promises';import path from 'node:path';import {fileURLToPath} from 'node:url';
const runtime=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
export const BROWSER_STANDING=path.resolve(runtime,'../public/v2/shell/standing.js');
export async function standingBrowserSource(){
 const source=await fs.readFile(path.join(runtime,'standing-rule.mjs'),'utf8');
 const names=[...source.matchAll(/^export (?:const|function) (\w+)/gm)].map(m=>m[1]);
 return '// Generated by runtime/scripts/build-standing.mjs from runtime/standing-rule.mjs. Do not edit; change the rule and run npm run build.\n'+source+'\nglobalThis.v2Standing = Object.freeze({'+names.join(', ')+'});\n';
}
export async function writeStandingBrowser(){await fs.writeFile(BROWSER_STANDING,await standingBrowserSource());}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))await writeStandingBrowser();
