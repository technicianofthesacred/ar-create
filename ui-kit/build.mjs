// Builds the parts page from coss ui's own code. Run: npm run build (inside ui-kit), or npm run build:ui at the root.
// 1. Lists every example coss's install put in src/components (p-<part>-<n>.tsx) into src/page/examples.gen.ts, each
//    loaded only when its part is opened, with its source text beside it.
// 2. Bundles the page with esbuild into public/ui/kit/ (one small file per example, loaded on demand).
// 3. Compiles Tailwind 4 (coss's styles plus AR Create's layer, src/app.css) into public/ui/kit/kit.css.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import { build } from "esbuild";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(here, "src");
const out = path.join(here, "..", "public", "ui", "kit");

const files = fs.readdirSync(path.join(src, "components")).filter((f) => /^p-.+-\d+\.tsx$/.test(f));
const examples = files
  .map((f) => { const m = f.match(/^p-(.+)-(\d+)\.tsx$/); return { file: f, part: m[1], n: Number(m[2]) }; })
  .sort((a, b) => a.part.localeCompare(b.part) || a.n - b.n);
const lines = examples.map((e) => `  { part: ${JSON.stringify(e.part)}, n: ${e.n}, name: ${JSON.stringify(e.file.replace(/\.tsx$/, ""))}, load: () => import("@/components/${e.file.replace(/\.tsx$/, "")}"), source: () => import("@/components/${e.file}?source") },`);
fs.writeFileSync(path.join(src, "page", "examples.gen.ts"),
  `// Generated by build.mjs from the examples coss's install wrote into src/components. Do not edit.\nimport type { Example } from "./types";\n\nexport const examples: Example[] = [\n${lines.join("\n")}\n];\n`);

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });

const sourceText = {
  name: "source-text",
  setup(b) {
    b.onResolve({ filter: /\?source$/ }, (a) => ({ path: path.join(src, a.path.replace(/^@\//, "").replace(/\?source$/, "")), namespace: "source" }));
    b.onLoad({ filter: /.*/, namespace: "source" }, (a) => ({ contents: fs.readFileSync(a.path, "utf8"), loader: "text" }));
  },
};

await build({
  entryPoints: [path.join(src, "page", "main.tsx")],
  outdir: out,
  bundle: true,
  splitting: true,
  format: "esm",
  minify: true,
  jsx: "automatic",
  target: "es2022",
  chunkNames: "chunks/[name]-[hash]",
  alias: { "@": src, "next/link": path.join(src, "shims", "next-link.tsx") },
  // Next.js settings the examples read. The address example falls back to sample addresses with no Maps key.
  define: { "process.env.NODE_ENV": '"production"', "process.env.NEXT_PUBLIC_GOOGLE_MAPS_API_KEY": '""' },
  loader: { ".woff2": "file", ".woff": "file" },
  plugins: [sourceText],
  logLevel: "warning",
});

// coss's style file imports the "geist" package, which only works inside Next.js. The same Geist Mono face comes from
// its plain package here; the build writes a copy with that one line swapped, and styles.css stays as installed.
fs.writeFileSync(path.join(src, "styles.build.css"), "/* Generated by build.mjs from styles.css. Do not edit. */\n" + fs.readFileSync(path.join(src, "styles.css"), "utf8").replace(/@import "geist";/, "@import \"@fontsource-variable/geist-mono\";"));
execFileSync(path.join(here, "node_modules", ".bin", "tailwindcss"), ["-i", path.join(src, "app.css"), "-o", path.join(out, "kit.css"), "--minify"], { cwd: here, stdio: "inherit" });

// The font packages' faces are linked as ./files/<name>; copy just the linked files next to kit.css.
fs.mkdirSync(path.join(out, "files"), { recursive: true });
const fontDirs = ["@fontsource-variable/inter", "@fontsource-variable/geist-mono"].map((p) => path.join(here, "node_modules", p, "files"));
for (const [, f] of fs.readFileSync(path.join(out, "kit.css"), "utf8").matchAll(/url\(\.\/files\/([^)]+)\)/g)) {
  const from = fontDirs.map((d) => path.join(d, f)).find((p) => fs.existsSync(p));
  if (!from) throw new Error("Font linked but not found: " + f);
  fs.copyFileSync(from, path.join(out, "files", f));
}

const total = fs.readdirSync(out, { recursive: true }).length;
console.log(`Parts page built: ${examples.length} examples from ${new Set(examples.map((e) => e.part)).size} parts, ${total} files in public/ui/kit.`);
