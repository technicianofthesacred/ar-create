#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

/**
 * Generates docs/status/CURRENT.md: the one short status page.
 *   node scripts/gen-status.mjs [--tests FILE] [--release RELEASE.json] [--works FILE] [--out FILE] [--check]
 *
 * --tests   a summary {tests,pass,fail,skipped,sha,at} written by CI, or the text of `node --test` TAP/spec output
 *           (its "# tests / # pass / # fail / # skipped" footer). Absent or unreadable: "Tests: not measured".
 * --release the installed <home>/RELEASE.json. Absent: "Installed release: not read".
 * --check   exit 1 if --out differs from what would be generated (writes nothing).
 * Nothing here reads a clock or the network, so the same inputs give the same page, and no number is ever invented.
 */
export const WORD_LIMIT = 1500;
const SHA = /^[a-f0-9]{7,40}$/;
const isCount = value => Number.isInteger(value) && value >= 0;
const group = n => n.toLocaleString('en-US');

/** Normalise a test summary object or TAP text to {tests,pass,fail,skipped,sha,at}, or null when it is not a real measurement. */
export function parseTests(text) {
  if (typeof text !== 'string' || !text.trim()) return null;
  let summary = null;
  if (text.trimStart().startsWith('{')) {
    try { summary = JSON.parse(text); } catch { return null; }
  } else {
    const pick = name => { const hit = text.match(new RegExp(`^# ${name} (\\d+)\\s*$`, 'm')); return hit ? Number(hit[1]) : null; };
    summary = { tests: pick('tests'), pass: pick('pass'), fail: pick('fail'), skipped: pick('skipped') ?? 0 };
  }
  if (!summary || typeof summary !== 'object') return null;
  const { tests, pass, fail } = summary, skipped = summary.skipped ?? 0;
  if (![tests, pass, fail, skipped].every(isCount)) return null;
  return { tests, pass, fail, skipped, sha: SHA.test(summary.sha ?? '') ? summary.sha : null, at: typeof summary.at === 'string' && summary.at.length <= 40 ? summary.at : null };
}
/** The record scripts/release.mjs writes, reduced to what the page prints. */
export function parseRelease(text) {
  try {
    const record = JSON.parse(text);
    if (!record || !SHA.test(record.sha ?? '')) return null;
    return { sha: record.sha, builtAt: typeof record.builtAt === 'string' ? record.builtAt : null, builtBy: typeof record.builtBy === 'string' ? record.builtBy : null, shipped: isCount(record.shipped) ? record.shipped : null };
  } catch { return null; }
}
const short = sha => sha.slice(0, 7);

export function testsLine(tests) {
  if (!tests) return 'Tests: not measured.';
  const where = [tests.sha ? `commit ${short(tests.sha)}` : null, tests.at].filter(Boolean).join(', ');
  return `Tests: ${group(tests.pass)} passed, ${group(tests.fail)} failed, ${group(tests.skipped)} skipped, of ${group(tests.tests)}${where ? ` (${where})` : ''}.`;
}
export function releaseLine(release, tests) {
  if (!release) return 'Installed release: not read.';
  const parts = [`commit ${short(release.sha)}`, release.builtAt ? `built ${release.builtAt}` : null, release.builtBy ? `by ${release.builtBy}` : null, release.shipped ? `${group(release.shipped)} files` : null].filter(Boolean);
  const drift = tests?.sha && tests.sha !== release.sha && !release.sha.startsWith(tests.sha) && !tests.sha.startsWith(release.sha) ? ` The tests above ran on a different commit (${short(tests.sha)}) than the one installed.` : '';
  return `Installed release: ${parts.join(', ')}.${drift}`;
}

/** The whole page. `works` is the text of docs/status/WORKS.md without its leading comment. */
export function buildStatus({ tests = null, release = null, works = '' } = {}) {
  const body = works.replace(/^<!--[\s\S]*?-->\s*/, '').trim();
  const page = [
    testsLine(tests),
    '',
    releaseLine(release, tests),
    '',
    '# AR Create: status',
    '',
    'This page is generated by `scripts/gen-status.mjs` from a measured test run, the installed `RELEASE.json` and the hand-kept list in [WORKS](WORKS.md). The first line is a measurement or it says "not measured"; it is never an estimate. Where this page and the code differ, the code wins.',
    '',
    body,
    '',
    '## Links',
    '',
    '- [Start here](../START.md): names, data map, conventions. [AGENTS](../../AGENTS.md): the entrance for every agent.',
    '- [PRODUCT](../product/PRODUCT.md): intent, then the dated decision log.',
    '- [CAPABILITIES](../CAPABILITIES.md): generated list of commands and tools. [TODO](../../TODO.md): open work.',
    '- [Status log, October 2026](../history/status-log-2026-10.md): the old running log of candidates and checkpoints, frozen.',
    '',
  ].join('\n');
  const words = page.split(/\s+/).filter(Boolean).length;
  if (words > WORD_LIMIT) throw new Error(`Status page is ${words} words; the limit is ${WORD_LIMIT}. Shorten docs/status/WORKS.md.`);
  return page;
}

function parseArgs(args) {
  const options = {};
  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    if (arg === '--check') options.check = true;
    else if (['--tests', '--release', '--works', '--out'].includes(arg) && args[i + 1] !== undefined) options[arg.slice(2)] = args[++i];
    else throw new Error(`Unknown or incomplete option ${arg}. Usage: gen-status.mjs [--tests FILE] [--release RELEASE.json] [--works FILE] [--out FILE] [--check]`);
  }
  return options;
}
const read = file => { try { return file ? fs.readFileSync(file, 'utf8') : null; } catch { return null; } };

export function generate(options, root = path.resolve(import.meta.dirname, '..')) {
  const works = read(options.works ?? path.join(root, 'docs/status/WORKS.md'));
  if (works === null) throw new Error('docs/status/WORKS.md is missing.');
  return buildStatus({ tests: parseTests(read(options.tests)), release: parseRelease(read(options.release)), works });
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const options = parseArgs(process.argv.slice(2)), root = path.resolve(import.meta.dirname, '..');
    const out = options.out ?? path.join(root, 'docs/status/CURRENT.md'), page = generate(options, root);
    if (options.check) { if (read(out) !== page) { console.error(`${out} is stale; run node scripts/gen-status.mjs.`); process.exitCode = 1; } }
    else { fs.writeFileSync(out, page); console.log(`${out}: ${page.split(/\s+/).filter(Boolean).length} words. ${page.split('\n')[0]}`); }
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
